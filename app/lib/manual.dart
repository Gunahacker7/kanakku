/// Manual entries (v0.8): the Add sheet writes both expenses and —
/// new in v0.8 — INCOME (Salary, Bonus, …). Manual entries persist
/// natively as a JSON list (manual_store). On-disk shape per entry:
///
///   {amount, label, ts, dir?, note?, category?, bucket?, mode?, tag?}
///
/// `dir` is written ONLY for income ("credit"); expenses omit it, so
/// stores saved by v0.1–v0.7 (no `dir` key at all) load unchanged as
/// debits. The helpers here are the single source of truth for that
/// format — the Shell loader, the persist path and the tests all go
/// through them.
///
/// v1.0.1: `category` (the user's picked category, mirrored from
/// `label`) and `bucket` (the picked Needs/Wants/Savings bucket) are
/// persisted explicitly — before this, a reload re-derived the
/// bucket from the merchant table and the Add sheet's note could
/// replace the picked subcategory entirely.
library;

import 'package:kanakku_parser/kanakku_parser.dart';
import 'package:kanakku_parser/categorize.dart';

import 'money.dart';

/// Income types offered in the Add sheet's Income mode. "Other"
/// reveals a custom-name field; the typed name becomes the label.
const incomeTypes = <String>[
  'Salary',
  'Bonus',
  'Freelance',
  'Interest',
  'Rental Income',
  'Refund / Cashback',
  'Gift',
  'Other',
];

/// Direction of a stored manual entry. Legacy JSON without a `dir`
/// key (or with anything but "credit") is an expense.
TxnDirection manualDirection(Map<String, dynamic> map) =>
    map['dir'] == 'credit' ? TxnDirection.credit : TxnDirection.debit;

/// Raw-body / identity string for a manual entry. Includes the
/// direction and label so an income and an expense of the same
/// amount saved in the same millisecond still get different entry
/// ids (entryId hashes the rawBody), and it is rebuilt identically
/// on every load, so ids are stable across restarts.
String manualRawBody(int ts, TxnDirection direction, String label) =>
    'Manual entry $ts|${direction.name}|$label';

/// Raw-body / identity string for a manual entry GENERATED by the
/// recurring engine (v1.1, spec §2.2). Deterministic in the rule id
/// and occurrence date — never in "now" — so a re-run of the engine
/// (or a restart mid-pass) rebuilds the identical entry id and the
/// crash-healing check can recognise an already-posted occurrence
/// instead of posting it twice.
String recurringRawBody(
  String ruleId,
  String occurrenceDate,
  TxnDirection direction,
  String label,
) => 'Recurring $ruleId|$occurrenceDate|${direction.name}|$label';

/// FNV-1a 32-bit hash (moved here from main.dart in v1.1 so the
/// recurring engine and the Shell compute identical entry ids).
/// Deterministic across runs and platforms.
String fnv1a(String s) {
  var h = 0x811c9dc5;
  for (final c in s.codeUnits) {
    h ^= c;
    h = (h * 0x01000193) & 0xffffffff;
  }
  return h.toRadixString(16);
}

/// Stable identity of any transaction (captured, manual, generated,
/// statement): parser dedupe key + timestamp + raw-body hash. The
/// removed-store, split records and recurring capture keys all speak
/// in these ids.
String entryId(ParsedTransaction t) =>
    '${t.dedupeKey}|${t.receivedAt.millisecondsSinceEpoch}|${fnv1a(t.rawBody)}';

/// Timestamp for a manual entry saved with the v0.9 date option:
/// the user-picked calendar [picked] date combined with the current
/// time-of-day from [now], so a backdated (or future-dated) entry
/// still orders naturally against same-day captured entries. The
/// result is what flows into the store's `ts` field — no format
/// change, and entry ids (which hash ts + label + direction) stay
/// unique across different picked dates.
DateTime manualStamp(DateTime picked, DateTime now) => DateTime(
  picked.year,
  picked.month,
  picked.day,
  now.hour,
  now.minute,
  now.second,
  now.millisecond,
);

/// Serialise one manual entry for the native store. v1.0 adds the
/// optional `mode` (payment mode: Cash/UPI/Card/Bank Transfer) and
/// `tag` (single free-text tag) — both omitted when unset, so
/// stores written by older versions keep loading unchanged.
Map<String, dynamic> manualToJson({
  required double amount,
  required String label,
  required DateTime at,
  required TxnDirection direction,
  String? note,
  Bucket? bucket,
  String? mode,
  String? tag,
  // v1.1 recurring provenance (spec §2.2): written only for
  // engine-generated entries.
  String? origin,
  String? recurringId,
  String? occurrenceDate,
  int? postedAtMs,
}) => {
  'amount': amount,
  // v1.1 dual-amount rule (spec §1.1): amountPaise is written
  // ATOMICALLY with amount, in the same object, on every path that
  // goes through this serialiser — the two can never drift apart.
  'amountPaise': paiseFromRupees(amount),
  'label': label,
  'category': label,
  'ts': at.millisecondsSinceEpoch,
  if (direction == TxnDirection.credit) 'dir': 'credit',
  if (bucket != null) 'bucket': bucket.name,
  if (note != null && note.isNotEmpty) 'note': note,
  if (mode != null && mode.isNotEmpty) 'mode': mode,
  if (tag != null && tag.isNotEmpty) 'tag': tag,
  'origin': ?origin,
  'recurringId': ?recurringId,
  'occurrenceDate': ?occurrenceDate,
  'postedAt': ?postedAtMs,
};

/// Decode an optional persisted bucket; old records return null and
/// keep their existing parser-derived bucket.
Bucket? manualBucketFromJson(Map<String, dynamic> map) {
  final value = map['bucket']?.toString();
  for (final bucket in Bucket.values) {
    if (bucket.name == value) return bucket;
  }
  return null;
}

/// Payment mode stored with a manual entry (v1.0); null when the
/// entry predates the field or none was chosen.
String? manualModeFromJson(Map<String, dynamic> map) {
  final m = map['mode']?.toString();
  return (m == null || m.isEmpty) ? null : m;
}

/// Tag stored with a manual entry (v1.0); null when absent/empty.
String? manualTagFromJson(Map<String, dynamic> map) {
  final t = map['tag']?.toString().trim();
  return (t == null || t.isEmpty) ? null : t;
}

/// Distinct tags present across manual entries, sorted — the
/// Transactions filter row is built from these.
List<String> distinctTags(Iterable<String?> tags) {
  final out = <String>{};
  for (final t in tags) {
    final v = t?.trim();
    if (v != null && v.isNotEmpty) out.add(v);
  }
  return out.toList()..sort();
}

/// Whether an entry with [tag] passes the active Transactions
/// filter ([filter] null = "All").
bool tagFilterPasses(String? tag, String? filter) =>
    filter == null || (tag != null && tag == filter);

/// The entry's amount in paise (spec §1.1 loader rule): the stored
/// `amountPaise` when present, otherwise converted from the legacy
/// double `amount` at read time. The store is never rewritten just
/// to backfill the field.
int manualAmountPaise(Map<String, dynamic> map) {
  final p = map['amountPaise'];
  if (p is num) return p.toInt();
  final a = map['amount'];
  return paiseFromRupees(a is num ? a.toDouble() : 0);
}

/// True for manual entries generated by the recurring engine
/// (spec §2.2 provenance marker).
bool manualIsRecurring(Map<String, dynamic> map) =>
    map['origin']?.toString() == 'recurring';

/// Apply a user edit to a stored manual entry (v1.1). The amount
/// edit recomputes `amountPaise` from the new `amount` IN THE SAME
/// write (spec §1.1 atomicity — test T-M4), and editing a
/// recurring-generated entry stamps `editedByUser`, which is what
/// stops the late-match sweep from ever auto-deleting it
/// (spec §3.3 step 4). Returns the mutated map for chaining.
Map<String, dynamic> applyManualEdit(
  Map<String, dynamic> map, {
  double? amount,
  String? note,
}) {
  if (amount != null) {
    map['amount'] = amount;
    map['amountPaise'] = paiseFromRupees(amount);
  }
  if (note != null) {
    if (note.isEmpty) {
      map.remove('note');
    } else {
      map['note'] = note;
    }
  }
  if (manualIsRecurring(map)) map['editedByUser'] = true;
  return map;
}

/// Rebuild the transaction for a stored manual entry.
ParsedTransaction manualTxnFromJson(Map<String, dynamic> map) {
  final label = map['label']?.toString() ?? '';
  final ts = (map['ts'] as num).toInt();
  final direction = manualDirection(map);
  // v1.1 (spec §2.2): generated entries rebuild their raw body from
  // the deterministic recurring form, so their entry id is the one
  // the engine computed when it posted them.
  final rawBody = manualIsRecurring(map)
      ? recurringRawBody(
          map['recurringId']?.toString() ?? '',
          map['occurrenceDate']?.toString() ?? '',
          direction,
          label,
        )
      : manualRawBody(ts, direction, label);
  return ParsedTransaction(
    // Spec §1.1 loader rule: amountPaise wins when present.
    amount: rupeesFromPaise(manualAmountPaise(map)),
    direction: direction,
    source: TxnSource.manual,
    receivedAt: DateTime.fromMillisecondsSinceEpoch(ts),
    rawBody: rawBody,
    counterparty: map['label']?.toString(),
  );
}

/// Optional free-text note stored with a manual entry; shown as
/// the transaction row subtitle. Null when absent/empty.
String? manualNoteFromJson(Map<String, dynamic> map) {
  final n = map['note']?.toString();
  return (n == null || n.isEmpty) ? null : n;
}
